'use strict';

// ============================================================
// Legal pages — privacy, cookies and terms, written from what
// the site actually does.
// ------------------------------------------------------------
// Every client site needs these three pages, and almost every one of them gets
// a copy-pasted policy that describes a site nobody built: a newsletter the
// client does not run, a payment processor they do not use, cookies that are
// never set. That is worse than having no page, because it is a false statement
// about data handling.
//
// Studio already knows the truth. It knows whether analytics is on and which
// provider it is, whether the cookie banner is on, where contact form posts go,
// whether a chat widget, booking link, map, video or shop was added, whether
// photos came from a stock library, and whether the fonts are fetched from
// Google. So these pages are generated from the project's own configuration
// and the cookie table lists only what the export really sets.
//
// Pure and offline: the module builds section data and hands it to the builder,
// which renders it with the site's own palette, fonts, nav and footer — so a
// legal page can never drift visually from the site it belongs to.
//
// This is a starting document, not legal advice. It is deliberately written to
// describe the site accurately and to be reviewed; the Studio settings panel
// says so, and each exported page carries the same note in an HTML comment.
// ============================================================

const Legal = (() => {

  const KINDS = ['privacy', 'cookies', 'terms'];
  const LABELS = { privacy: 'Privacy Policy', cookies: 'Cookie Policy', terms: 'Terms of Use' };
  // Where the page's own note about its provenance goes, invisible to visitors.
  const NOTE = '<!-- Generated by PallettAI Studio from this site\u2019s own configuration. '
    + 'It describes what this site actually does, but it is a starting document: have it reviewed before you rely on it. -->';

  const esc = (s) => String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

  const dateStamp = (d) => {
    const dt = d ? new Date(d) : new Date();
    if (Number.isNaN(dt.getTime())) return '';
    return dt.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
  };

  // Which form-delivery service the export actually posts to. Mirrors the
  // classification in Builder.deliveryFor so the policy names the right company.
  function formProvider(raw) {
    const v = String(raw || '').trim();
    if (!v) return '';
    if (/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v)) return 'FormSubmit';
    if (/formspree\.io/i.test(v)) return 'Formspree';
    if (/web3forms\.com/i.test(v)) return 'Web3Forms';
    if (/^https?:\/\//i.test(v)) return 'a third-party form service';
    return 'Web3Forms';
  }

  const BOOKING_LABELS = {
    calendly: 'Calendly', calcom: 'Cal.com', tidycal: 'TidyCal',
    youcanbookme: 'YouCanBookMe', square: 'Square Appointments', custom: 'a third-party booking service'
  };

  // The host named by an embed URL (video / embed sections), so the policy can
  // name the real third party instead of "external content".
  function embedHost(url) {
    const m = String(url || '').match(/^https?:\/\/([^/?#]+)/i);
    const host = (m && m[1] || '').toLowerCase().replace(/^www\./, '');
    if (!host) return '';
    if (/youtube|youtu\.be/.test(host)) return 'YouTube';
    if (/vimeo/.test(host)) return 'Vimeo';
    if (/spotify/.test(host)) return 'Spotify';
    if (/typeform/.test(host)) return 'Typeform';
    if (/figma/.test(host)) return 'Figma';
    if (/google/.test(host)) return 'Google';
    return host;
  }

  // Photo libraries whose licence requires (or merits) a mention.
  function photoSources(site) {
    const found = new Set();
    const walk = (obj) => {
      if (!obj || typeof obj !== 'object') return;
      if (Array.isArray(obj)) { obj.forEach(walk); return; }
      const meta = obj.imageMeta;
      if (meta && typeof meta === 'object') {
        const label = String(meta.source || meta.provider || '').toLowerCase();
        if (label.includes('openverse')) found.add('Openverse');
        else if (label.includes('wikimedia') || label.includes('commons')) found.add('Wikimedia Commons');
        else if (label.includes('pixabay')) found.add('Pixabay');
        else if (label.includes('flickr')) found.add('Flickr');
        else if (meta.license || meta.attribution) found.add('an open-licence photo library');
      }
      ['items', 'sections', 'posts', 'products', 'tiers'].forEach((k) => { if (Array.isArray(obj[k])) obj[k].forEach(walk); });
    };
    walk(site.sections);
    (Array.isArray(site.pages) ? site.pages : []).forEach((pg) => walk(pg.sections));
    return Array.from(found);
  }

  // Everything this site really does, read from the model + export settings.
  function facts(project, settings) {
    const site = (project && project.site) || {};
    const s = settings || {};
    const suites = (project && project.suites) || [];
    const pages = (Array.isArray(site.pages) && site.pages.length)
      ? site.pages
      : [{ sections: Array.isArray(site.sections) ? site.sections : [] }];
    const every = [];
    pages.forEach((pg) => (Array.isArray(pg.sections) ? pg.sections : []).forEach((sec) => every.push(sec)));
    const has = (type) => every.some((sec) => sec && sec.type === type);
    const first = (type) => every.find((sec) => sec && sec.type === type) || null;

    const analyticsId = String(s.analyticsId || '').trim();
    const analyticsProvider = s.analyticsProvider === 'plausible' ? 'plausible' : 'ga4';
    const booking = first('booking');
    const embeds = ['video', 'embed'].map((t) => first(t)).filter(Boolean)
      .map((sec) => embedHost(sec.extra || sec.bookingUrl || '')).filter(Boolean);
    const chatOn = !!(site.chatWidget && (site.chatWidget.propertyId || site.chatWidget.id || site.chatWidget.enabled));
    const shopOn = suites.includes('shop') || has('shop');

    return {
      site, s, suites,
      // The keys the export actually writes (see builder.js storageFor). Named
      // after the client, because this table is printed on the client's own
      // cookie policy — the studio's tooling has no business being in it.
      storage: storageKeysFor(project),
      name: String(site.name || (project && project.name) || 'this business').replace(/\s+—\s+Website$/, ''),
      email: String(site.email || '').trim(),
      phone: String(site.phone || '').trim(),
      address: String(site.address || '').trim(),
      area: String(site.area || '').trim(),
      hasAnalytics: !!analyticsId,
      analyticsProvider,
      hasCookieBanner: s.cookieBanner === true,
      forms: formProvider(site.formEndpoint),
      hasForms: !!(site.formEndpoint || has('contact')),
      chatOn,
      hasBooking: !!booking,
      bookingLabel: booking ? (BOOKING_LABELS[booking.bookingProvider] || BOOKING_LABELS.custom) : '',
      embeds: Array.from(new Set(embeds)),
      hasMap: has('map'),
      shopOn,
      hasReviews: has('reviews') || suites.includes('reviews'),
      hasEvents: has('events') || suites.includes('events'),
      hasThemeToggle: site.themeToggle !== false,
      fonts: s.onlineEnabled !== false,
      photoSources: photoSources(site),
      translation: (site.translation && site.translation.provider)
        ? (site.translation.provider === 'deepl' ? 'DeepL' : site.translation.provider === 'mymemory' ? 'MyMemory' : '')
        : ''
    };
  }

  // ---- clause copy -----------------------------------------------------------

  function whoWeAre(fx) {
    const lines = ['This policy explains how ' + fx.name + ' handles personal information collected through this website.'];
    const reach = [];
    if (fx.email) reach.push('email ' + fx.email);
    if (fx.phone) reach.push('telephone ' + fx.phone);
    if (fx.address) reach.push('post at ' + fx.address);
    if (reach.length) lines.push('You can reach us by ' + reach.join(', ') + '.');
    if (fx.area) lines.push('We are based in ' + fx.area + '.');
    return lines.join(' ');
  }

  function collected(fx) {
    const out = [];
    if (fx.hasForms) out.push({ title: 'Enquiry details', text: 'Whatever you type into a form on this site — usually your name, email address, phone number and your message.' });
    if (fx.shopOn) out.push({ title: 'Order and basket details', text: 'The items you add to the basket, and the contact details you give us so we can fulfil an order.' });
    if (fx.hasBooking) out.push({ title: 'Appointment details', text: 'The name, contact details and timing you enter when booking an appointment.' });
    if (fx.hasAnalytics) {
      out.push({
        title: 'How the site is used',
        text: fx.analyticsProvider === 'plausible'
          ? 'Aggregate, cookieless statistics about pages viewed, referrers and country. This is not tied to you as an individual.'
          : 'Statistics about pages viewed, how you arrived and roughly where you are, collected by Google Analytics 4 using cookies (see our Cookie Policy).'
      });
    }
    if (fx.chatOn) out.push({ title: 'Live chat conversations', text: 'The messages you send us in the chat widget, and the contact details you leave there.' });
    out.push({ title: 'Technical information', text: 'Standard server and security logs — IP address, browser type and the pages requested — kept to run the site safely.' });
    return out;
  }

  function purposes(fx) {
    const out = [{ title: 'To answer you', text: 'We use your enquiry details to reply and to provide the service you asked about. Our lawful basis is our legitimate interest in responding to business enquiries, or the contract we are about to enter with you.' }];
    if (fx.shopOn) out.push({ title: 'To fulfil orders', text: 'We use order details to take payment, deliver what you bought and handle returns. The lawful basis is the contract between us, and our legal obligations on records.' });
    if (fx.hasBooking) out.push({ title: 'To run appointments', text: 'We use appointment details to schedule, remind you and keep our own records. The lawful basis is the contract between us.' });
    if (fx.hasAnalytics) out.push({ title: 'To understand the site', text: 'We use usage statistics to see which pages help people and which do not. Where the provider uses cookies, our lawful basis is your consent, which you can withdraw at any time.' });
    out.push({ title: 'To keep the site secure', text: 'We use technical logs to detect abuse and keep the site available. Our lawful basis is our legitimate interest in a secure service.' });
    return out;
  }

  function sharedWith(fx) {
    const out = [];
    if (fx.forms) out.push({ title: fx.forms, text: 'Form submissions on this site are delivered through ' + fx.forms + '. They process the message on our behalf so it reaches our inbox.' });
    if (fx.hasAnalytics) out.push({ title: fx.analyticsProvider === 'plausible' ? 'Plausible Analytics' : 'Google Analytics', text: fx.analyticsProvider === 'plausible' ? 'Privacy-focused, cookieless analytics for this site.' : 'Measures how the site is used. Google may process this data outside the country you are in, under its own safeguards.' });
    if (fx.chatOn) out.push({ title: 'Tawk.to', text: 'Provides the live chat widget, and processes the messages you send through it.' });
    if (fx.hasBooking) out.push({ title: fx.bookingLabel, text: 'The scheduling service that takes your appointment booking — their own privacy policy applies to the details you enter.' });
    if (fx.hasMap) out.push({ title: 'Google Maps', text: 'An embedded map loads directly from Google, which will see your IP address when the page displays it.' });
    fx.embeds.forEach((host) => out.push({ title: host, text: 'Embedded media loads directly from ' + host + ', which will see your IP address when it plays.' }));
    if (fx.fonts) out.push({ title: 'Google Fonts', text: 'Some typefaces on this site are loaded from Google\u2019s font service, which receives your IP address when your browser requests them.' });
    if (fx.photoSources.length) out.push({ title: fx.photoSources.join(' and '), text: 'Some photographs on this site come from open-licence libraries; where a credit is required it appears in the site footer.' });
    if (fx.translation) out.push({ title: fx.translation, text: 'Provides machine translation of this site\u2019s text where a translated view is offered.' });
    out.push({ title: 'Nobody else', text: 'We do not sell your personal information. We share it only with the services listed above, or where the law requires it.' });
    return out;
  }

  function retained(fx) {
    const parts = [];
    if (fx.hasForms) parts.push('Enquiries are kept for as long as we need them to help you, and then for a reasonable period in case you come back to us.');
    if (fx.shopOn) parts.push('Order records are kept for the period our tax and accounting rules require.');
    if (fx.hasAnalytics) parts.push(fx.analyticsProvider === 'plausible' ? 'Analytics for this site are aggregate and are not tied to an individual.' : 'Analytics data is retained according to the provider\u2019s own retention settings.');
    parts.push('Security logs are kept for a short period and then discarded.');
    return parts.join(' ');
  }

  function rights(fx) {
    const reach = fx.email ? 'email ' + fx.email : 'use the contact details on this site';
    return 'You can ask for a copy of the personal information we hold about you, ask us to correct or delete it, object to how we are using it, or ask us to restrict what we do with it. '
      + 'To do any of that, ' + reach + '. We will respond within the time the law allows. '
      + 'If you are not happy with our response you can complain to the data protection authority in your country.';
  }

  /*
    The same storage namespace the builder writes under.

    data/whitelabel.js derives it from the site's own name, and this file must
    agree with it exactly: a policy that lists a key the site never sets, or
    omits one it does, is the most common lie on a small business site. The
    local fallback keeps this file honest if it is loaded without the module.
  */
  function storageKeysFor(project) {
    if (typeof Whitelabel !== 'undefined' && Whitelabel.storageKeys) return Whitelabel.storageKeys(project);
    const p = String((project && project.site && project.site.name) || 'site').toLowerCase().replace(/[^a-z0-9]+/g, '').slice(0, 24) || 'site';
    return { prefix: p, theme: p + '_theme_', themeGlob: p + '_theme_*', consent: p + '_cookies_ok', cart: p + '_cart_', cartGlob: p + '_cart_*' };
  }

  // ---- cookie rows -----------------------------------------------------------
  // Only storage the export actually sets earns a row. A "cookies" table full of
  // entries the site never writes is the single most common lie on a small site.

  function storageRows(fx) {
    const rows = [];
    const local = (name, purpose, duration) => rows.push([name, 'Local storage', purpose, duration]);
    const keys = fx.storage || storageKeysFor(null);
    if (fx.hasCookieBanner) local(keys.consent, 'Remembers your cookie choice so we do not ask again', 'Until you clear your browser storage');
    if (fx.hasThemeToggle) local(keys.themeGlob, 'Remembers whether you prefer the light or dark version of this site', 'Until you clear your browser storage');
    if (fx.shopOn) local(keys.cartGlob, 'Keeps the contents of your basket while you browse', 'Until you clear your browser storage');

    if (fx.hasAnalytics && fx.analyticsProvider === 'ga4') {
      rows.push(['_ga', 'Cookie', 'Distinguishes one visitor from another so we can count visits', 'Up to 2 years']);
      rows.push(['_ga_*', 'Cookie', 'Keeps the state of your analytics session', 'Up to 2 years']);
    }

    if (!rows.length) {
      rows.push(['—', 'None', 'This site does not set cookies or store anything in your browser', '—']);
    }
    return rows;
  }

  function cookieClauses(fx) {
    const out = [];
    out.push({
      title: 'What cookies are',
      text: 'Cookies are small files a site asks your browser to store. This site also uses local storage, which works in a similar way but never leaves your device. Neither contains your name or email address.'
    });
    if (fx.hasAnalytics && fx.analyticsProvider === 'ga4') {
      out.push({
        title: 'Analytics cookies',
        text: 'Google Analytics 4 sets the cookies below to measure how this site is used. They are only set after you accept them — if you decline, or never choose, no analytics cookies are stored and the analytics script does not load.'
      });
    } else if (fx.hasAnalytics) {
      out.push({
        title: 'Analytics without cookies',
        text: 'This site uses Plausible Analytics, which measures visits without cookies and without identifying individual visitors. There is nothing to consent to, and nothing to decline.'
      });
    }
    if (fx.hasCookieBanner) {
      out.push({
        title: 'Your choice',
        text: 'When you first arrive, a banner asks whether you accept analytics cookies. Accepting loads analytics immediately; declining leaves them switched off. Either way we remember your answer, and you can change it by clearing your browser storage for this site.'
      });
    }
    out.push({
      title: 'Managing cookies in your browser',
      text: 'Every browser lets you see, block and delete cookies and site data, usually under Settings, Privacy or History. Blocking everything may break parts of other sites you use, but this site will still work.'
    });
    return out;
  }

  // ---- terms clauses ---------------------------------------------------------

  function termsClauses(fx) {
    const out = [];
    out.push({ title: 'Who you are dealing with', text: whoWeAre(fx) + ' These terms cover your use of this website.' });
    out.push({ title: 'Using this site', text: 'You are welcome to read, browse and share this site. Please do not attempt to break it, scrape it at a volume that degrades it for others, or use it in a way that is unlawful.' });
    out.push({ title: 'Quotes, prices and availability', text: 'Prices, menus, opening hours and availability shown on this site are a guide and can change. A quote or booking only becomes binding when we confirm it in writing.' });
    if (fx.shopOn) out.push({ title: 'Orders', text: 'An order is accepted when we confirm it. If something you ordered is unavailable, or a price was clearly wrong, we will contact you and refund anything you have paid before we cancel.' });
    if (fx.hasBooking) out.push({ title: 'Appointments', text: 'Appointments are booked through ' + (fx.bookingLabel || 'a scheduling service') + '. Their terms also apply to the booking itself. Please give us as much notice as you can if you need to cancel or move one.' });
    out.push({ title: 'Our content', text: 'The words, layout and design of this site belong to ' + fx.name + ' or are used with permission. Photographs carry their own licences, shown in the footer where a credit is required. Please ask before reusing anything from the site.' });
    out.push({ title: 'Other sites we link to', text: 'Where we link to someone else\u2019s site, we do not control it and we are not responsible for what it says or does.' });
    out.push({ title: 'How far our responsibility goes', text: 'We take care to keep this site accurate and available, but we do not promise it will always be uninterrupted or error-free. Nothing in these terms limits our liability where the law does not allow it to be limited — including for death or personal injury caused by our negligence, or for fraud.' });
    out.push({ title: 'Which law applies', text: 'These terms are governed by the law of the country in which ' + fx.name + ' operates, and any dispute will be handled by the courts of that country.' });
    out.push({ title: 'Changes', text: 'If we change these terms we will update the date at the top of this page. Continuing to use the site means you accept the version published here.' });
    return out;
  }

  function privacyClauses(fx) {
    const out = [];
    out.push({ title: 'Who we are', text: whoWeAre(fx) });
    out.push({ title: 'What we collect', text: collected(fx).map((c) => c.text).join(' ') });
    out.push({ title: 'Why we use it', text: purposes(fx).map((c) => c.title.toLowerCase() + ' — ' + c.text.replace(/^We use /, 'we use ')).join(' ') });
    out.push({ title: 'Who else sees it', text: sharedWith(fx).map((c) => c.title).filter((t) => t !== 'Nobody else').join(', ') + '. We do not sell your personal information, and we share it only with those services or where the law requires it.' });
    out.push({ title: 'How long we keep it', text: retained(fx) });
    out.push({ title: 'Sending information abroad', text: 'Some of the services above are based outside your country, so your information may be processed there. Where that happens, the provider relies on the safeguards set out in its own privacy policy, such as standard contractual clauses.' });
    out.push({ title: 'Your rights', text: rights(fx) });
    out.push({ title: 'Cookies', text: 'This site uses cookies and local storage as described in our Cookie Policy, which is linked in the footer of every page.' });
    out.push({ title: 'Changes to this policy', text: 'If what we do changes, we will update this page and the date at the top of it.' });
    return out;
  }

  // ---- page assembly ---------------------------------------------------------

  function intro(kind, fx) {
    if (kind === 'cookies') {
      return 'What this site stores in your browser, why it does, and how to turn it off.';
    }
    if (kind === 'terms') {
      return 'The basis on which you use the ' + fx.name + ' website.';
    }
    return 'How ' + fx.name + ' collects, uses and protects personal information, and what you can ask us to do about it.';
  }

  function clausesFor(kind, fx) {
    if (kind === 'cookies') return cookieClauses(fx);
    if (kind === 'terms') return termsClauses(fx);
    return privacyClauses(fx);
  }

  // A builder-shaped section that renders the clause list as numbered rows —
  // readable prose with real headings, not an accordion nobody opens.
  function clauseSection(fx, heading, clauses) {
    return {
      type: 'features',
      layout: 'numbered',
      title: heading,
      subtitle: '',
      text: '',
      animation: 'fade-up',
      items: clauses.map((c) => ({ icon: '§', title: c.title, text: c.text, extra: '', tag: '' }))
    };
  }

  function pageSections(kind, fx) {
    const out = [{
      type: 'hero',
      layout: 'minimal',
      title: LABELS[kind],
      subtitle: intro(kind, fx),
      text: 'Last updated ' + dateStamp(),
      ctaText: '',
      ctaLink: '',
      animation: 'fade-in'
    }];
    if (kind === 'cookies') {
      out.push({
        type: 'table',
        layout: '',
        title: 'What this site stores in your browser',
        subtitle: 'This table lists everything the site actually sets — nothing is listed that it does not use.',
        cols: ['Name', 'Kind', 'Purpose', 'How long'],
        rows: storageRows(fx),
        animation: 'fade-up'
      });
      out.push(clauseSection(fx, 'About cookies on this site', cookieClauses(fx)));
    } else {
      out.push(clauseSection(fx, kind === 'terms' ? 'The terms' : 'In detail', clausesFor(kind, fx)));
    }
    out.push({
      type: 'contact',
      title: 'Questions about this page',
      subtitle: fx.email ? 'Email ' + fx.email + ' and we will answer as soon as we can.' : 'Use the contact details on this site and we will answer as soon as we can.',
      animation: 'fade-up'
    });
    return out;
  }

  function page(project, settings, kind) {
    const fx = facts(project, settings);
    const label = LABELS[kind] || 'Legal';
    return {
      id: 'pg-legal-' + kind,
      name: label,
      slug: kind,
      // Rendered and linked from the footer, never in the main navigation.
      hidden: true,
      legal: kind,
      sections: pageSections(kind, fx)
    };
  }

  function enabled(settings) {
    return !!(settings && settings.legalPages === true);
  }

  // The pages the export should carry, or an empty list when the feature is off.
  function pages(project, settings) {
    if (!enabled(settings)) return [];
    return KINDS.map((kind) => page(project, settings, kind));
  }

  /*
    A copy of the project with the legal pages appended to its page list.

    Used by the builder's page and sitemap paths so one integration point covers
    ZIP export, publish, client handoff and the delivery report. The clone is
    shallow on purpose: projects carry base64 photos and deep-cloning one on
    every export would cost megabytes for nothing.
  */
  function attach(project, settings) {
    if (!project || !project.site || !enabled(settings)) return project;
    const pagesList = (Array.isArray(project.site.pages) && project.site.pages.length)
      ? project.site.pages.slice()
      : [{ id: 'pg-home', name: 'Home', slug: 'index', sections: Array.isArray(project.site.sections) ? project.site.sections : [] }];
    const existing = new Set(pagesList.map((pg) => pg && pg.slug));
    const added = KINDS.filter((k) => !existing.has(k)).map((kind) => page(project, settings, kind));
    if (!added.length) return project;
    const site = Object.assign({}, project.site, { pages: pagesList.concat(added) });
    return Object.assign({}, project, { site });
  }

  // Footer row. Quiet, small, and present on every page of the export.
  // `data-legal` names the file each link opens, which the Studio's live preview
  // uses to show the page in the frame — the pages are not in the project's
  // page list, so the preview has no other way to resolve them.
  function footerLinks(settings) {
    if (!enabled(settings)) return '';
    return `<p class="foot-legal">${KINDS.map((k) => `<a href="${k}.html" data-legal="${k}">${esc(LABELS[k])}</a>`).join(' · ')}</p>`;
  }

  return {
    KINDS, LABELS, NOTE,
    enabled, facts, pages, page, attach, footerLinks,
    storageRows, storageKeysFor, clausesFor, dateStamp, esc,
    formProvider, embedHost
  };
})();

if (typeof module !== 'undefined' && module.exports) module.exports = Legal;

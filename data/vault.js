// ============================================================
// PallettAI Studio — cloud project vault (pure logic)
// Merge/payload engine behind Settings ▸ Cloud backup. No DOM,
// no fetch — the app drives it against SUPABASE and the smoke
// test drives it against the mock registry.
//
// Merge rules (content-aware last-writer-wins, delete-wins-over-stale):
//   * Identical content (the merge clock ignored), whatever the timestamps say
//     → nothing. A device never re-adopts or re-pushes its own last push, and
//     two clocks that disagree about an unchanged project can never
//     manufacture a conflict.
//   * Same updatedAt but different content → adopt cloud, archiving the diverged
//     local as a 'conflict' version first (every device converges on the same
//     cloud row; the losing edit stays restorable)
//   * Local newer than the cloud payload's own updatedAt → push local
//   * Cloud payload newer, local content differs → adopt cloud, and the
//     DIVERGED local copy is flagged so the caller can file it as a 'conflict'
//     version first — a lost race never means lost work
//   * Tombstoned (deleted) in cloud → the delete wins unless the local copy
//     holds a genuinely newer edit (different content, later payload clock),
//     which survives as a resurrection push — never a device-vs-server clock race
//
// Clock-safety note: only timestamps generated by the SAME clock are ever
// compared. Payload updatedAt values come from device clocks (they travel
// inside the payload, and that is why they are stripped from the CONTENT
// comparison); the server's row.updatedAt is never compared with a device
// clock at all — a tombstone is decided by the payload it archived.
// ============================================================

'use strict';

const Vault = (() => {
  const MAX_PUSH_BYTES = 6 * 1024 * 1024; // mirrors the RPC ceiling (measured in UTF-8 bytes)

  // Whole-project JSON string for the vault. `null` when the project cannot
  // be serialized (corrupt model) — callers skip it.
  function serializeProject(p) {
    try { return JSON.stringify(p || null); } catch (e) { return null; }
  }

  // UTF-8 byte length — the unit the registry actually measures
  // (`octet_length(v_payload::text)`). String#length counts UTF-16 code units,
  // so emoji and accented copy measure short here while the server sees the
  // real (larger) size: a project could pass the client check only to be
  // refused server-side, or blow past the ceiling after a wasted round-trip.
  function byteLength(s) {
    const str = String(s == null ? '' : s);
    try {
      if (typeof TextEncoder !== 'undefined') return new TextEncoder().encode(str).length;
    } catch (e) { /* no TextEncoder — fall through */ }
    return str.length; // last-resort code-unit approximation
  }

  // Basic shape check for a cloud payload before it is adopted as a project.
  function looksLikeProject(p) {
    return !!(p && typeof p === 'object' && p.site && typeof p.site === 'object'
      && Array.isArray(p.site.sections) && typeof p.id === 'string' && p.id);
  }

  // Stable JSON equality. Key order never matters; undefined fields and
  // absent fields are the same thing. Used to tell "same edit, two clocks"
  // apart from "two real edits" — the difference between a no-op and a push.
  function eq(a, b) {
    if (a === b) return true;
    try { return JSON.stringify(canon(clean(a))) === JSON.stringify(canon(clean(b))); } catch (e) { return false; }
  }
  // Canonical form: keys sorted at every depth, so JSON.stringify equality
  // is structural. Runs at sync frequency (a couple of comparisons per
  // project), never per keystroke — correctness is worth the walk.
  function canon(v) {
    if (Array.isArray(v)) return v.map(canon);
    if (v && typeof v === 'object') {
      const out = {};
      Object.keys(v).sort().forEach((k) => { out[k] = canon(v[k]); });
      return out;
    }
    return v;
  }
  // Strip the two fields that describe a payload rather than are one, before a
  // structural comparison:
  //   * `vault` — the cloud bookkeeping withVaultMeta attaches; without
  //     stripping it every adopt would immediately look like fresh divergence.
  //   * `updatedAt` — the merge clock. It travels inside the payload so it can
  //     be compared with other payload clocks, but two devices holding the SAME
  //     site at different times are not in conflict: a timestamp-only
  //     difference is not content, and treating it as one is what caused both
  //     the self-adopt churn and phantom 'conflict' archives.
  function clean(p) {
    if (!p || typeof p !== 'object') return p;
    const c = Object.assign({}, p);
    delete c.vault;
    delete c.updatedAt;
    return c;
  }

  // Attach cloud bookkeeping to an adopted project without changing its identity.
  function withVaultMeta(p, row) {
    try {
      const copy = JSON.parse(JSON.stringify(p));
      copy.vault = { updatedAt: (row && row.updatedAt) || Date.now(), syncedAt: Date.now() };
      return copy;
    } catch (e) { return p; }
  }

  // ---------- plan(): what should happen for each cloud row ----------
  // locals: array of local projects (full models)
  // rows:   array of { projectId, name, payload, updatedAt, deletedAt }
  // Returns {
  //   toPush:     [project]  — local-newer or diverged-local-wins
  //   toAdopt:    [project]  — cloud-newer or local-absent
  //   toDropLocal:[id]       — cloud tombstone beats the local copy
  //   conflicts:  [{ id, winner, at }] — destructive overwrites the caller
  //               should archive first ('conflict' versions), so a lost
  //               merge race is recoverable from vault history
  // }
  function plan(locals, rows) {
    const byId = new Map();
    (Array.isArray(locals) ? locals : []).forEach((p) => {
      if (p && typeof p.id === 'string' && p.id) byId.set(p.id, p);
    });

    const toPush = [];
    const toAdopt = [];
    const toDropLocal = [];
    const conflicts = [];
    const seen = new Set();

    (Array.isArray(rows) ? rows : []).forEach((row) => {
      if (!row || !row.projectId || seen.has(row.projectId)) return;
      seen.add(row.projectId);
      const local = byId.get(row.projectId);

      if (row.deletedAt) {
        // Deleted in the cloud. A tombstoned row still carries the payload it
        // held when it was deleted, so this decision uses CONTENT and payload
        // clocks — never the server stamp against a device clock, which is how
        // a machine with a fast clock resurrects what another machine
        // deliberately deleted.
        //   * local identical to the deleted state → the delete wins
        //   * local genuinely newer (different content, later payload clock) →
        //     real work the delete never saw; keep it as a resurrection push
        //   * anything else (stale, or a payload we cannot read) → delete wins
        // Either way the row never reaches the adopt path: its payload predates
        // the delete and must not be adopted. The delete RPC archived the live
        // payload, so every deletion stays restorable from vault history.
        if (!local) return;
        const archived = looksLikeProject(row.payload) ? row.payload : null;
        if (archived && eq(local, archived)) { toDropLocal.push(local.id); return; }
        const localAt = local.updatedAt || local.createdAt || 0;
        const archivedAt = (archived && archived.updatedAt) || 0;
        if (localAt > archivedAt) { toPush.push(local); return; }
        toDropLocal.push(local.id);
        return;
      }

      if (!local) {
        // Only exists in the cloud (or was resurrected there): adopt it.
        if (looksLikeProject(row.payload)) toAdopt.push(row.payload);
        return;
      }

      const localAt = local.updatedAt || local.createdAt || 0;
      const cloudPayload = looksLikeProject(row.payload) ? row.payload : null;
      const cloudAt = (cloudPayload && cloudPayload.updatedAt) || 0;

      if (cloudPayload && eq(local, cloudPayload)) {
        // Identical content — the quiet no-op that keeps a settled sync from
        // bouncing the same project back and forth forever. Checked BEFORE
        // either timestamp picks a winner, so two clocks that disagree about
        // an unchanged project never re-adopt it, re-push it, or flag a
        // phantom conflict. This is also what ends churn for payloads that
        // predate updatedAt stamping: identical content is identical, dated
        // or not.
        return;
      }
      if (!cloudAt || localAt > cloudAt) {
        // Local is genuinely newer (or the cloud payload is not a usable
        // project): push. When this overwrites a different cloud state, the
        // server's version guard archives it (the push carries local.updatedAt).
        toPush.push(local);
        return;
      }
      // Cloud is newer and the content differs — the local copy really
      // diverged. Flag it: the caller files the losing local state as a
      // 'conflict' version BEFORE overwriting it.
      conflicts.push({ id: local.id, winner: 'cloud', at: cloudAt });
      toAdopt.push(row.payload);
    });

    // Cloud has never heard of these: push everything the account owns.
    byId.forEach((p, id) => { if (!seen.has(id)) toPush.push(p); });

    return { toPush, toAdopt, toDropLocal, conflicts };
  }

  // ---------- payload for one push ----------
  // Returns { ok, projectId, name, payload } or { ok: false, reason }.
  function pushPayload(p) {
    const json = serializeProject(p);
    if (json == null) return { ok: false, reason: 'serialize' };
    const bytes = byteLength(json);
    if (bytes > MAX_PUSH_BYTES) return { ok: false, reason: 'too-large', size: bytes };
    return { ok: true, projectId: p.id, name: String((p.site && p.site.name) || p.name || 'Untitled'), payload: p };
  }

  // ---------- one push round (given a save function) ----------
  // saveFn(projectId, name, payload) → { ok } — provided by the caller
  // (app.js binds SUPABASE.saveProjectBackup; the smoke test binds the
  // mock RPC through SUPABASE too). Never throws; per-project failures
  // are collected so one bad project cannot abort the whole sync.
  async function pushAll(projects, saveFn) {
    const results = { pushed: 0, failed: 0, skipped: 0, errors: [] };
    for (const p of Array.isArray(projects) ? projects : []) {
      const prep = pushPayload(p);
      if (!prep.ok) { results.skipped++; results.errors.push({ id: p && p.id, reason: prep.reason }); continue; }
      try {
        const r = await saveFn(prep.projectId, prep.name, prep.payload, null, p.updatedAt);
        if (r && r.ok) results.pushed++;
        else { results.failed++; results.errors.push({ id: prep.projectId, reason: (r && r.msg) || 'save failed' }); }
      } catch (e) {
        results.failed++;
        results.errors.push({ id: prep.projectId, reason: (e && e.message) || 'save failed' });
      }
    }
    return results;
  }

  return { plan, pushPayload, pushAll, serializeProject, looksLikeProject, withVaultMeta, eq, byteLength, MAX_PUSH_BYTES };
})();

if (typeof module !== 'undefined' && module.exports) module.exports = Vault;

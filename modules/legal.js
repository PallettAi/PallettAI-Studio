// ============================================================
// PallettAI Studio — legal & GDPR compliance generator
// Privacy/terms documents + a privacy-first consent banner.
// ------------------------------------------------------------
//   1. generatePrivacyPolicy(siteDetails) → [{name, content}, …]
//      Builds complete privacy.html and terms.html documents from
//      what the business actually is: business type decides which
//      data points, payments, accounts and retention rows exist;
//      region decides the governing regime (UK GDPR / EU GDPR /
//      CCPA-CPRA / PIPEDA / Australian Privacy Act / generic) and
//      the rights + governing-law clauses. The two pages cross-link.
//
//   2. generateCookieConsentScript(options) → string
//      A zero-cookie banner: the consent decision lives in
//      localStorage, never document.cookie. Honours Do Not Track
//      (navigator/window/msDoNotTrack) and Global Privacy Control
//      as an automatic opt-out — those visitors are never prompted
//      because the answer is already known. GDPR: nothing
//      non-essential loads before an explicit Accept, Decline is
//      offered equally, and the choice can be withdrawn at any time
//      via window.__paiConsent. CCPA: optional "Do Not Sell or
//      Share" link plus GPC opt-out above.
//
// ---- what this file guarantees ----------------------------------
// 1. THE POLICY NEVER CLAIMS A PRACTICE THE CONFIG DOESN'T SET.
//    No shop flag → no orders/shipments clause; no analytics flag →
//    no analytics processor named. A policy that lies about data
//    handling is worse than no policy.
// 2. EVERY INTERPOLATED STRING IS ESCAPED — a hostile business name
//    becomes text in the document, never live markup.
// 3. THE CONSENT SCRIPT SETS NO COOKIES, EVER. It reads/writes one
//    localStorage key and loads nothing itself; the analytics starter
//    (window.__paiAnalytics, the hook exported sites already use) is
//    called only after an explicit, stored Accept.
// 4. THIS IS A STARTING DOCUMENT, NOT LEGAL ADVICE — each generated
//    page carries that note in an HTML comment and in the footer, the
//    same posture data/legal.js takes.
//
// Pure string generation: no network, no DOM, no storage here.
// ============================================================

// ---- escaping (same contract as Builder.esc) ------------------------
const esc = (s) => String(s == null ? '' : s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

const NOTE = '<!-- Generated by PallettAI Studio from this site\u2019s own details. '
  + 'It is a starting document, not legal advice: have it reviewed before you rely on it. -->';


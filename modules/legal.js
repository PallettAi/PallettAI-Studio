// ============================================================
// Task 3.2 — zero-cookie consent banner script
// ============================================================
//
// NOTE ON CONSTRUCTION: everything below this line is assembled as
// one string of JS source, so comments about the *generated* script
// live above, never between the concatenation lines — a module-level
// // comment dropped between two + '…' lines would itself become
// source text in the output.
//
//
// options = {
//   storageKey?    localStorage key (default 'site_consent')
//   privacyUrl?    default 'privacy.html'
//   termsUrl?      default 'terms.html'
//   doNotSellUrl?  CCPA link; shown when region is US/US-CA
//   region?        'US' | 'US-CA' | 'UK' | 'EU' | …
//   analyticsHook? window function to start after Accept
//                  (default '__paiAnalytics' — the hook exports use)
//   bannerText?    copy override
// }
//
// Returns a self-contained IIFE string. Behaviour:
//   stored Accept        → start analytics, no banner
//   stored Decline       → nothing, no banner
//   DNT or GPC signal    → treated as Decline, banner suppressed
//                          (the answer is already known; asking again
//                          would be a dark pattern)
//   nothing stored       → banner with equal Accept / Decline
//
// It never writes document.cookie and never fetches anything itself.
function generateCookieConsentScript(options) {
  const o = options || {};
  const cfg = {
    key: String(o.storageKey || 'site_consent').replace(/[^\w:.-]/g, '') || 'site_consent',
    privacy: String(o.privacyUrl || 'privacy.html'),
    terms: String(o.termsUrl || 'terms.html'),
    doNotSell: o.doNotSellUrl ? String(o.doNotSellUrl) : '',
    ccpa: ['US', 'US-CA'].indexOf(normalizeRegion(o.region)) !== -1,
    hook: String(o.analyticsHook || '__paiAnalytics').replace(/[^\w.$]/g, '') || '__paiAnalytics',
    text: String(o.bannerText || 'We use cookies only with your consent. You can accept or decline, '
      + 'and change your mind at any time.')
  };

  // Every string below is JS SOURCE in the output: config arrives via
  // JSON.stringify (never markup), copy enters the DOM via textContent,
  // and no comment may sit between two concatenation lines.
  return '(function(){'
    + 'var CFG=' + JSON.stringify(cfg) + ';'
    + 'var el=null;'
    + 'var choice=null;'
    + 'function read(){try{return localStorage.getItem(CFG.key);}catch(e){return null;}}'
    + 'function write(v){try{if(v===null)localStorage.removeItem(CFG.key);else localStorage.setItem(CFG.key,v);}catch(e){}}'
    // DNT (all three spellings) + GPC: visitor-expressed opt-outs,
    // honoured without prompting — the answer is already known.
    + 'function optOut(){'
    + 'try{if(String(navigator.doNotTrack)==="1"||String(window.doNotTrack)==="1"'
    + '||String(navigator.msDoNotTrack)==="1")return true;}catch(e){}'
    + 'try{if(navigator.globalPrivacyControl===true)return true;}catch(e){}'
    + 'return false;'
    + '}'
    + 'function start(){var fn=window[CFG.hook];if(typeof fn==="function"){try{fn();}catch(e){}}}'
    + 'function stop(){var fn=window[CFG.hook+"Stop"];if(typeof fn==="function"){try{fn();}catch(e){}}}'
    + 'function hide(){if(el&&el.parentNode)el.parentNode.removeChild(el);el=null;}'
    // The single state writer: stored value, side effect, banner out.
    + 'function decide(v){choice=v;write(v);if(v==="granted")start();else stop();hide();}'
    + 'function show(){'
    + 'if(el||choice)return;'
    + 'el=document.createElement("div");'
    + 'el.setAttribute("role","dialog");'
    + 'el.setAttribute("aria-modal","false");'
    + 'el.setAttribute("aria-label","Cookie consent");'
    + 'el.style.cssText="position:fixed;left:12px;right:12px;bottom:12px;z-index:9999;'
    + 'max-width:560px;margin:0 auto;padding:14px 16px;border-radius:12px;'
    + 'background:#0b1220;color:#e8ecf5;box-shadow:0 12px 40px rgba(0,0,0,.35);'
    + 'font:14px/1.5 system-ui,sans-serif;display:flex;gap:12px;flex-wrap:wrap;align-items:center";'
    + 'var msg=document.createElement("span");'
    + 'msg.style.cssText="flex:1 1 240px";'
    + 'msg.textContent=CFG.text;'
    + 'el.appendChild(msg);'
    + 'function btn(label,solid){'
    + 'var b=document.createElement("button");'
    + 'b.type="button";b.textContent=label;'
    + 'b.style.cssText="padding:8px 16px;border-radius:8px;font:inherit;font-weight:600;cursor:pointer;"'
    + '+(solid?"border:1px solid #2f6fed;background:#2f6fed;color:#fff"'
    + ':"border:1px solid #4b5563;background:transparent;color:#e8ecf5")'
    + '+";flex:0 0 auto";'
    + 'return b;'
    + '}'
    + 'var links=document.createElement("span");'
    + 'links.style.cssText="flex:1 1 100%;font-size:12px;display:flex;gap:14px;flex-wrap:wrap";'
    + 'function link(label,href){'
    + 'var a=document.createElement("a");'
    + 'a.textContent=label;a.href=href;a.rel="noopener";'
    + 'a.style.cssText="color:#7aa5ff";'
    + 'return a;'
    + '}'
    + 'links.appendChild(link("Privacy Policy",CFG.privacy));'
    + 'links.appendChild(link("Terms",CFG.terms));'
    + 'if(CFG.ccpa&&CFG.doNotSell)links.appendChild(link("Do Not Sell or Share My Personal Information",CFG.doNotSell));'
    + 'el.appendChild(links);'
    + 'var no=btn("Decline",false);'
    + 'var yes=btn("Accept",true);'
    + 'no.addEventListener("click",function(){decide("denied");});'
    + 'yes.addEventListener("click",function(){decide("granted");});'
    + 'el.appendChild(no);el.appendChild(yes);'
    + 'document.body.appendChild(el);'
    + '}'
    // Public API: a site can offer "Cookie settings" anywhere.
    + 'window.__paiConsent={'
    + 'get:function(){return read();},'
    + 'accept:function(){decide("granted");},'
    + 'decline:function(){decide("denied");},'
    + 'revoke:function(){write(null);choice=null;stop();hide();},'
    + 'show:function(){choice=read();hide();if(!choice)show();},'
    + 'optedOut:optOut'
    + '};'
    + 'choice=read();'
    + 'if(choice===null&&optOut()){choice="denied";write(choice);}'
    + 'if(choice==="granted")start();'
    + 'if(!choice){'
    + 'if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",show);'
    + 'else show();'
    + '}'
    + '})();';
}


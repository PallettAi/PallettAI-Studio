    + '<style>\n'
    + ':root{color-scheme:light dark;--t:#0b1220;--m:#4b5563;--l:#e5e7eb;--a:#2f6fed}'
    + '@media (prefers-color-scheme:dark){:root{--t:#e8ecf5;--m:#9aa4b6;--l:#28324a;--a:#7aa5ff}}'

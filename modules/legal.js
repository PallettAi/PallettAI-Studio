const TYPE_ALIASES = {
  ecommerce: 'ecommerce', shop: 'ecommerce', store: 'ecommerce', retail: 'ecommerce',
  saas: 'saas', software: 'saas', app: 'saas', platform: 'saas',
  service: 'service', agency: 'service', local: 'service', professional: 'service',
  content: 'content', blog: 'content', media: 'content', publication: 'content',
  nonprofit: 'nonprofit', charity: 'nonprofit',
  portfolio: 'portfolio'
};

const REGION_ALIASES = {
  uk: 'UK', gb: 'UK', 'united kingdom': 'UK',
  eu: 'EU', eea: 'EU', europe: 'EU',
  us: 'US', usa: 'US',
  'us-ca': 'US-CA', california: 'US-CA', 'us-ca-gdpr': 'US-CA',
  ca: 'CA', canada: 'CA',
  au: 'AU', australia: 'AU'
};

function normalizeType(raw) {
  const k = String(raw || '').trim().toLowerCase();
  return TYPE_ALIASES[k] || 'service';
}

function normalizeRegion(raw) {
  const k = String(raw || '').trim().toLowerCase();
  return REGION_ALIASES[k] || 'generic';
}


// What the business actually collects/does. Flags override the
// type-derived defaults; false flags always win so an explicitly
// switched-off feature can never sneak back into the prose.
function policyFacts(siteDetails) {
  const d = siteDetails || {};
  const type = normalizeType(d.businessType || d.type);
  const region = normalizeRegion(d.region || d.country);
  const flags = d.flags || d.collects || {};

  const has = (key, typeDefault) => {
    if (flags[key] === false || d[key] === false) return false;
    if (flags[key] === true || d[key] === true) return true;
    return !!typeDefault;
  };

  const facts = {
    name: String(d.businessName || d.name || 'the site operator'),
    domain: String(d.domain || deriveDomain(d.url) || ''),
    url: String(d.url || (d.domain ? 'https://' + d.domain : '')),
    email: String(d.email || d.contactEmail || ''),
    type,
    region,
    regime: regimeFor(region),
    effective: String(d.effectiveDate || defaultDate()),

    shop: has('shop', type === 'ecommerce'),
    accounts: has('accounts', type === 'saas'),
    forms: has('forms', type !== 'portfolio'),
    newsletter: has('newsletter', false),
    comments: has('comments', false),
    analytics: has('analytics', false),
    booking: has('booking', false),
    chat: has('chat', false),
    donations: has('donations', type === 'nonprofit'),

    paymentProvider: String(d.paymentProvider || flags.paymentProvider || ''),
    formProvider: detectFormProvider(d.formEndpoint || d.forms || flags.formEndpoint || ''),
    analyticsProvider: String(d.analyticsProvider || flags.analyticsProvider || ''),
    hosting: String(d.hosting || flags.hosting || '')
  };
  // Shop implies payments even if nobody set the flag.
  if (facts.shop) facts.payments = true;
  return facts;
}

function deriveDomain(url) {
  const m = String(url || '').match(/^https?:\/\/([^/?#]+)/i);
  return m ? m[1].replace(/^www\./, '') : '';
}

// Only ever names a service the config literally points at.
function detectFormProvider(raw) {
  const v = String(raw || '').trim();
  if (!v) return '';
  if (/formspree\.io/i.test(v)) return 'Formspree';
  if (/web3forms\.com/i.test(v)) return 'Web3Forms';
  if (/getform\.io/i.test(v)) return 'GetForm';
  if (/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(v)) return 'an email delivery service';
  if (/^https?:\/\//i.test(v)) return 'a third-party form service';
  return '';
}

function defaultDate() {
  const d = new Date();
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
}

// ============================================================
// Task 3.1 — privacy.html + terms.html
// ============================================================
//
// Returns zip-ready file entries ({name, content}) so the export
// pipeline can consume them without a wrapper object.
function generatePrivacyPolicy(siteDetails) {
  const f = policyFacts(siteDetails);
  return [
    { name: 'privacy.html', content: privacyDocument(f) },
    { name: 'terms.html', content: termsDocument(f) }
  ];
}


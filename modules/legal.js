function contactBlock(f) {
  if (!f.email) return '';
  return '<p>Privacy questions: <a href="mailto:' + esc(f.email) + '">' + esc(f.email) + '</a></p>';
}

// ---- data-point rows per business type ------------------------------
function collectedSections(f) {
  const rows = [];
  rows.push('<h2>What we collect</h2>');
  const items = [];

  if (f.forms) {
    items.push('the details you send through our contact or enquiry form (typically your name, '
      + 'email address and whatever you write to us)');
  }
  if (f.accounts) {
    items.push('account details you provide when registering (name, email address and password \u2014 '
      + 'passwords are stored only as hashes)');
    items.push('billing details for your subscription and basic usage data needed to run and secure the service');
  }
  if (f.shop) {
    items.push('order details: the products you buy, your name, delivery address and contact details');
    items.push('payment information \u2014 processed by '
      + (f.paymentProvider ? esc(f.paymentProvider) : 'our payment processor')
      + '; we never see or store your full card number');
  }
  if (f.donations) {
    items.push('donation details (amount, name and receipt email) processed by our payment provider');
  }
  if (f.newsletter) {
    items.push('your email address and subscription preferences if you sign up to our newsletter');
  }
  if (f.comments) {
    items.push('the content of comments you leave and the name you sign them with');
  }
  if (f.booking) {
    items.push('appointment or booking details (date, time and contact information)');
  }
  if (f.analytics) {
    items.push('standard technical data such as pages visited, device and browser type, general location '
      + 'and referral source, collected by '
      + (f.analyticsProvider ? esc(f.analyticsProvider) : 'our analytics provider')
      + ' to help us understand how the site is used');
  }
  items.push('technical data the server logs automatically, such as IP address, requested URL and request time, '
    + 'kept for security and abuse prevention');

  items.forEach((i) => { rows.push('<li>' + i + '</li>'); });
  rows.push('</ul>');
  // Open the list right after the heading.
  return rows[0] + '<ul>' + rows.slice(1).join('');
}

function privacyDocument(f) {
  const r = f.regime;
  const name = esc(f.name);
  const parts = [];

  parts.push('<h1>Privacy Policy</h1>');
  parts.push('<p class="meta">Effective ' + esc(f.effective)
    + (f.domain ? ' \u00b7 ' + esc(f.domain) : '') + '</p>');

  parts.push('<h2>Who we are</h2>');
  parts.push('<p>' + name + (f.domain ? ' (' + esc(f.domain) + ')' : '')
    + ' operates this website. In this policy, \u201cwe\u201d means ' + name
    + '. We are the controller of the personal data described here under ' + esc(r.laws) + '.</p>');
  if (f.email) {
    parts.push('<p>Contact: <a href="mailto:' + esc(f.email) + '">' + esc(f.email) + '</a></p>');
  }

  parts.push(collectedSections(f));

  parts.push('<h2>Why we use it</h2><ul>');
  if (f.forms || f.booking) parts.push('<li>To answer enquiries and deliver the services you ask for (steps before a contract, or performance of a contract).</li>');
  if (f.shop || f.donations) parts.push('<li>To process orders and donations, take payment and send receipts (performance of a contract).</li>');
  if (f.accounts) parts.push('<li>To create and secure your account and provide the service (performance of a contract and legitimate interests in keeping the service safe).</li>');
  if (f.newsletter) parts.push('<li>To send the newsletter you subscribed to \u2014 based on your consent, withdrawable in every email.</li>');
  if (f.analytics) parts.push('<li>To understand aggregated usage and improve the site (legitimate interests; loaded only after you consent where required).</li>');
  parts.push('<li>To protect the site against abuse and keep it secure (legitimate interests).</li>');
  parts.push('</ul>');

  parts.push('<h2>Cookies and local storage</h2>');
  parts.push('<p>This site is privacy-first: the consent banner stores your choice in your browser\u2019s '
    + 'local storage rather than a cookie, and the site itself sets no tracking cookies before you agree to them.'
    + (f.analytics ? ' Analytics runs only after you accept.' : ' No analytics or advertising cookies are used.') + '</p>');
  if (f.shop || f.accounts) {
    parts.push('<p>Strictly necessary storage may be used to keep you signed in or to hold your basket '
      + 'while you shop; these do not require consent because the site cannot function without them.</p>');
  }

  parts.push('<h2>Who we share it with</h2><ul>');
  if (f.hosting) parts.push('<li>' + esc(f.hosting) + ' \u2014 hosting this website.</li>');
  else parts.push('<li>Our hosting provider, which runs this website.</li>');
  if (f.formProvider) parts.push('<li>' + esc(f.formProvider) + ' \u2014 delivering form submissions to us.</li>');
  if (f.shop || f.donations) parts.push('<li>' + (f.paymentProvider ? esc(f.paymentProvider) : 'Our payment processor')
    + ' \u2014 taking payment; they handle card data under PCI-DSS.</li>');
  if (f.analytics && f.analyticsProvider) parts.push('<li>' + esc(f.analyticsProvider) + ' \u2014 anonymised usage statistics.</li>');
  if (f.chat) parts.push('<li>Our live-chat provider \u2014 answering messages you send.</li>');
  if (f.newsletter) parts.push('<li>Our email newsletter provider \u2014 sending the newsletter you asked for.</li>');
  parts.push('<li>Professional advisers and authorities where the law requires us to disclose information.</li>');
  parts.push('</ul>');
  parts.push('<p>We do <strong>not</strong> sell your personal information.</p>');

  parts.push('<h2>How long we keep it</h2><ul>');
  if (f.shop || f.donations) parts.push('<li>Order and donation records: up to 7 years, to meet tax and accounting duties.</li>');
  if (f.accounts) parts.push('<li>Account data: while your account is open, then deleted or anonymised within 90 days of closure.</li>');
  if (f.forms || f.booking) parts.push('<li>Enquiries and booking requests: up to 12 months after we last correspond.</li>');
  if (f.newsletter) parts.push('<li>Newsletter subscription: until you unsubscribe.</li>');
  if (f.analytics) parts.push('<li>Analytics data: for the retention period set by '
    + (f.analyticsProvider ? esc(f.analyticsProvider) : 'our analytics provider') + '.</li>');
  parts.push('<li>Server logs: for up to 30 days, for security.</li>');
  parts.push('</ul>');

  parts.push('<h2>Your rights</h2>');
  parts.push('<p>Under ' + esc(r.laws) + ' you may:</p><ul>');
  r.rights.forEach((right) => { parts.push('<li>' + right + '</li>'); });
  parts.push('</ul>');
  parts.push('<p>' + esc(r.complaint) + '</p>');
  if (r.ccpa) {
    parts.push('<p>We do not sell your personal information. To make a rights request as a '
      + (f.region === 'US-CA' ? 'California resident' : 'US resident')
      + ', contact us using the address below and we will respond within the time the law allows.</p>');
  }

  if (f.region === 'UK' || f.region === 'EU' || f.region === 'AU') {
    parts.push('<h2>International transfers</h2>');
    parts.push('<p>Where our providers process data outside your country, we rely on the safeguards the law '
      + 'provides for such transfers (for example adequacy decisions or standard contractual clauses).</p>');
  }

  parts.push('<h2>Children</h2>');
  parts.push('<p>This site is not directed at children under 16, and we do not knowingly collect their data. '
    + 'If you believe a child has provided information to us, contact us and we will delete it.</p>');

  parts.push('<h2>Changes to this policy</h2>');
  parts.push('<p>We may update this page when our practices or the law change. The effective date at the top '
    + 'shows when the current version took effect.</p>');

  parts.push('<h2>Contact</h2>');
  parts.push(contactBlock(f) || '<p>Use the contact details published on this site to reach us.</p>');
  parts.push('<p>Read our <a href="terms.html">Terms of Use</a> for the rules that apply to using this site.</p>');
  parts.push('<p class="disc">This document was generated from the site\u2019s own configuration and is a '
    + 'starting point, not legal advice.</p>');

  return pageDoc('Privacy Policy', f, parts.join('\n'));
}


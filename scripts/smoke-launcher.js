'use strict';

/*
  Boot the REAL application for a smoke, once.

  app-smoke and widget-studio-smoke both need exactly the same thing: the
  actual Electron app, started against the project root exactly as `npm start`
  does, with an observer in the MAIN process (the `hook`) and a driver that
  runs INSIDE the renderer (the `page`). The app is never replaced or mocked —
  a smoke that boots a stand-in measures the stand-in.

  app-smoke solves the same problem with its own inline copy, and is left as it
  is on purpose: it is the release gate's flagship, and refactoring a passing
  gate for tidiness is how a green suite becomes an untested one. New real-app
  suites use this module so the quirks live in one place; every line in it was
  found the hard way:

    · the binary path, read from electron's path.txt because `require('electron')`
      installs Electron's own shims into a plain Node process and quietly breaks
      the harness;
    · a throwaway userData directory, because the app persists projects in the
      real profile and a suite that inherits them measures the free plan's
      project cap instead of the feature;
    · an entry file that MUST sit at the project root, because Electron sets
      app.getAppPath() to the directory of the script it is given and main.js's
      loadFile('index.html') resolves against that;
    · --no-sandbox for the TEST PROCESS ONLY (a CI checkout cannot own the
      SUID helper) — never added to the app, where the sandbox is a security
      boundary rather than an inconvenience.

  Two suites can run at once (ci-run-all-tests uses --jobs), so the entry file
  is named per suite and the profile is per run.
*/

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn } = require('child_process');

const ROOT = path.join(__dirname, '..');

/*
  Electron writes a wall of GPU/EGL noise on machines without hardware
  acceleration — which is every headless CI runner. That noise is not a failure
  and must not be mistaken for one, so it is filtered out of the child's output.
  Everything else is passed through untouched, because a real error is the whole
  point of running this.
*/
const NOISE = /EGL|GLDisplay|viz_main_impl|gl_display|gl_initializer|task_policy_set|Failed to connect to the bus|dbus|libva|DevTools listening/;

/**
 * launchRealApp({ hook, page, entryName, timeoutMs }) -> { code, out, timedOut, error }
 *   hook       absolute path to the main-process observer, run before main.js
 *   page       absolute path to the in-page driver the observer injects
 *   entryName  scratch entry file at the project root, unique per suite
 *   timeoutMs  hang guard; a hung renderer must not hang the gate
 */
function launchRealApp(options) {
  const opts = options || {};
  const { hook, page, entryName } = opts;
  const timeoutMs = Math.max(1000, Number(opts.timeoutMs) || 180000);
  const ENTRY = path.join(ROOT, entryName || '.smoke-entry.js');

  return new Promise((resolve) => {
    const candidates = [];
    const distDir = path.join(ROOT, 'node_modules', 'electron', 'dist');
    try {
      const rel = fs.readFileSync(path.join(ROOT, 'node_modules', 'electron', 'path.txt'), 'utf8').trim();
      if (rel) candidates.push(path.join(distDir, rel));
    } catch (e) { /* no path.txt — fall through to the known layouts */ }
    if (process.platform === 'darwin') {
      candidates.push(path.join(distDir, 'Electron.app', 'Contents', 'MacOS', 'Electron'));
    } else if (process.platform === 'win32') {
      candidates.push(path.join(distDir, 'electron.exe'));
    } else {
      candidates.push(path.join(distDir, 'electron'));
    }

    const electronBin = candidates.find((p) => fs.existsSync(p));
    if (!electronBin) {
      resolve({
        code: null,
        out: '',
        timedOut: false,
        error: 'the Electron binary is not installed at any of: ' + candidates.join(', ')
          + '\n     Electron downloads its binary in a postinstall script. If npm was'
          + ' told to skip scripts, run: node node_modules/electron/install.js'
      });
      return;
    }

    // ELECTRON_RUN_AS_NODE is deliberately NOT set here, and is deleted if the
    // environment has it: it is present in some CI images and would make the
    // binary behave as plain Node, loading the driver with no Electron runtime.
    const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'pallettai-smoke-'));

    const env = Object.assign({}, process.env, {
      ELECTRON_DISABLE_SECURITY_WARNINGS: '1',
      PALLETTAI_SMOKE_HOOK: hook
    });
    if (page) env.PALLETTAI_SMOKE_PAGE = page;
    delete env.ELECTRON_RUN_AS_NODE;

    fs.writeFileSync(ENTRY, [
      "'use strict';",
      '// Generated by scripts/smoke-launcher.js. Installs the observer, then boots the',
      '// real application entry. Nothing about the app is replaced.',
      'require(' + JSON.stringify(hook) + ');',
      'require(' + JSON.stringify(path.join(ROOT, 'main.js')) + ');',
      ''
    ].join('\n'));

    const launchArgs = [ENTRY, '--user-data-dir=' + profile];
    if (process.platform === 'linux') launchArgs.push('--no-sandbox', '--disable-dev-shm-usage');

    const child = spawn(electronBin, launchArgs, {
      cwd: ROOT,
      env: env,
      stdio: ['ignore', 'pipe', 'pipe']
    });

    let out = '';
    const collect = (buf) => {
      const text = String(buf);
      out += text;
      text.split('\n').forEach((line) => {
        // A Chromium FATAL aborts the process before any window exists. Keep it:
        // it is the single most useful line when a smoke fails on a machine that
        // differs from the developer's.
        if (line.trim() && (!NOISE.test(line) || /FATAL/.test(line))) {
          process.stdout.write('    ' + line + '\n');
        }
      });
    };
    child.stdout.on('data', collect);
    child.stderr.on('data', collect);

    child.on('error', (e) => { out += '\nSPAWN_ERROR ' + e.message; });

    const cleanup = () => {
      // The entry is scratch, not a source file — remove it whatever happens,
      // and take the throwaway profile with it.
      try { fs.unlinkSync(ENTRY); } catch (e) { /* already gone */ }
      try { fs.rmSync(profile, { recursive: true, force: true }); } catch (e) { /* best effort */ }
    };

    const timer = setTimeout(() => {
      try { child.kill('SIGKILL'); } catch (e) { /* already gone */ }
      cleanup();
      resolve({ code: null, out, timedOut: true });
    }, timeoutMs);

    child.on('close', (code) => {
      clearTimeout(timer);
      cleanup();
      resolve({ code, out, timedOut: false });
    });
  });
}

/**
 * The observer's result block, parsed rather than grepped: a passing word in an
 * error message must never be able to fake a pass.
 */
const RESULT_RE = /SMOKE_RESULT (\{[\s\S]*?\})\s*SMOKE_END/;
function parseResult(out) {
  const m = String(out || '').match(RESULT_RE);
  if (!m) return null;
  try { return JSON.parse(m[1]); } catch (e) { return null; }
}

module.exports = { launchRealApp, parseResult, ROOT };
